#!/usr/bin/env python3
"""把中英双语补丁注入 P4-CAN 的 dashboard_source.html。

用法（在任意目录执行，只依赖标准库）：
    python3 apply_zh.py <仓库根目录>              # 只注入/更新 dashboard_source.html
    python3 apply_zh.py <仓库根目录> --build      # 注入后重新生成 index_html.h（等同跑 tools/build_dashboard.py）
    python3 apply_zh.py <仓库根目录> --revert     # 移除补丁，恢复纯英文
    python3 apply_zh.py <仓库根目录> --check      # 只报告当前是否已注入

设计：注入块用 <!--P4ZH-BEGIN--> / <!--P4ZH-END--> 包起来，重复执行只会替换这一段，
不会叠加。补丁本身只给元素加 data-p4zh 属性，靠 CSS ::after 显示中文，
不改任何原有文本节点，删掉即完全恢复英文。
"""

import argparse
import gzip
import re
import sys
from pathlib import Path

BEGIN = '<!--P4ZH-BEGIN-->'
END = '<!--P4ZH-END-->'
HERE = Path(__file__).resolve().parent


def read_patch() -> str:
    js = (HERE / 'zh-bilingual.js').read_text(encoding='utf8')
    return f'{BEGIN}\n<script>\n{js}\n</script>\n{END}\n'


def strip_existing(html: str) -> str:
    return re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n?', '', html, flags=re.S)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('repo', help='P4-CAN 仓库根目录（含 dashboard_source.html）')
    ap.add_argument('--build', action='store_true', help='注入后重新生成 index_html.h')
    ap.add_argument('--revert', action='store_true', help='移除补丁')
    ap.add_argument('--check', action='store_true', help='只检查状态')
    args = ap.parse_args()

    root = Path(args.repo).expanduser().resolve()
    src = root / 'dashboard_source.html'
    if not src.is_file():
        print(f'找不到 {src}', file=sys.stderr)
        return 2

    html = src.read_text(encoding='utf8')
    injected = BEGIN in html

    if args.check:
        print('已注入' if injected else '未注入')
        return 0

    if args.revert:
        if not injected:
            print('本来就没注入，无需处理')
            return 0
        src.write_text(strip_existing(html), encoding='utf8')
        print(f'已移除补丁：{src}')
    else:
        if '</body>' not in html:
            print('dashboard_source.html 里找不到 </body>，结构可能已变化', file=sys.stderr)
            return 3
        body = strip_existing(html)
        new_html = body.replace('</body>', read_patch() + '</body>', 1)
        src.write_text(new_html, encoding='utf8')
        print(f'{"已更新" if injected else "已注入"}补丁：{src}（{len(new_html)} 字节）')

    if args.build:
        header = root / 'index_html.h'
        data = gzip.compress(src.read_bytes(), mtime=0)
        lines = [', '.join(f'0x{x:02X}' for x in data[i:i + 16]) for i in range(0, len(data), 16)]
        content = ('#pragma once\n#include <Arduino.h>\n'
                   '// Generated by tools/build_dashboard.py\n'
                   'static const uint8_t INDEX_HTML_GZ[] PROGMEM = {\n' +
                   ',\n'.join(lines) + '\n};\n'
                   'static const size_t INDEX_HTML_GZ_LEN = ' + str(len(data)) + ';\n')
        header.write_text(content, encoding='utf8')
        print(f'已重新生成 {header}（gzip {len(data)} 字节）')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
